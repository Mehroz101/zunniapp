// ── 5. Canonical & International Hreflang Constructor ──
export function runCanonicalHreflangGenerator(input: string, options?: Record<string, any>): ToolExecutionResult {
  const startTime = performance.now();
  const baseUrl = (options?.baseUrl || 'https://example.com').trim().replace(/\/+$/, '');

  const localeMap: Record<string, string> = {
    'en': `${baseUrl}/`,
    'es': `${baseUrl}/es/`,
    'fr': `${baseUrl}/fr/`,
    'de': `${baseUrl}/de/`,
    'ja': `${baseUrl}/ja/`,
    'x-default': `${baseUrl}/`,
  };

  if (input.trim()) {
    input.split('\n').forEach((l) => {
      const parts = l.split(/[:=,\s]+/).map((s) => s.trim()).filter(Boolean);
      if (parts.length >= 2) {
        localeMap[parts[0].toLowerCase()] = parts[1];
      }
    });
  }

  let tags = `<!-- Canonical Link -->\n`;
  tags += `<link rel="canonical" href="${localeMap['en'] || localeMap['x-default'] || baseUrl}" />\n\n`;
  tags += `<!-- Multi-Regional / Multi-Lingual Hreflang Clusters -->\n`;

  for (const [lang, url] of Object.entries(localeMap)) {
    tags += `<link rel="alternate" hreflang="${lang}" href="${url}" />\n`;
  }

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: tags,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: tags.length },
    meta: { localeMap, totalLocales: Object.keys(localeMap).length },
  };
}

// ── 6. SERP Snippet & Pixel Width Calculator ──
export function runSerpSimulator(input: string, options?: Record<string, any>): ToolExecutionResult {
  const startTime = performance.now();
  const data: Record<string, string> = {};

  input.split('\n').forEach((l) => {
    const idx = l.indexOf(':');
    if (idx > -1) {
      data[l.slice(0, idx).trim().toLowerCase()] = l.slice(idx + 1).trim();
    }
  });

  const title = data.title || options?.title || 'AIIsEverything — AI Tools, News & Guides For Everyone';
  const url = data.url || options?.url || 'https://aiiseverything.com/ai-tools/coding/json-to-typescript';
  const description = data.description || data.desc || options?.description || 'Discover the best free AI developer tools, stay ahead with daily neural model breakthroughs, and master modern programming workflows with zero paywalls.';

  // Proportional font character widths (Approximating Arial 20px for Title and Arial 14px for Description)
  const calcPixelWidth = (text: string, charScale: number): number => {
    let px = 0;
    for (const ch of text) {
      if (/[ilI1\.,;:\'!]/.test(ch)) px += 4 * charScale;
      else if (/[wWmMOQ@]/.test(ch)) px += 11 * charScale;
      else if (/[A-Z]/.test(ch)) px += 9 * charScale;
      else if (/[fjt ]/.test(ch)) px += 5 * charScale;
      else px += 7 * charScale;
    }
    return Math.round(px);
  };

  const titlePx = calcPixelWidth(title, 1.25);
  const descPx = calcPixelWidth(description, 0.95);

  const titleCeiling = 600; // Google desktop title truncation limit
  const descCeiling = 960;  // Google desktop description truncation limit

  const titleTruncated = titlePx > titleCeiling;
  const descTruncated = descPx > descCeiling;

  let report = `====================================================\n`;
  report += `GOOGLE SERP SNIPPET AUDIT & PIXEL METRICS\n`;
  report += `====================================================\n\n`;

  report += `Title: "${title}"\n`;
  report += `• Length: ${title.length} characters\n`;
  report += `• Pixel Width: ${titlePx}px / ${titleCeiling}px max\n`;
  report += `• Status: ${titleTruncated ? '⚠️ TRUNCATED BY GOOGLE (Exceeds 600px ceiling)' : '✅ PERFECT FIT (100% visible on SERP)'}\n\n`;

  report += `URL: ${url}\n\n`;

  report += `Meta Description:\n"${description}"\n`;
  report += `• Length: ${description.length} characters\n`;
  report += `• Pixel Width: ${descPx}px / ${descCeiling}px max\n`;
  report += `• Status: ${descTruncated ? '⚠️ TRUNCATED BY GOOGLE (Exceeds 960px ceiling)' : '✅ OPTIMAL LENGTH (Full snippet display)'}\n\n`;

  report += `Generated HTML Meta Tags:\n`;
  report += `<title>${title}</title>\n`;
  report += `<meta name="description" content="${description}" />\n`;
  report += `<link rel="canonical" href="${url}" />\n`;

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: report,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: report.length },
    meta: {
      title,
      url,
      description,
      titlePx,
      descPx,
      titleTruncated,
      descTruncated,
    },
  };
}

// ── 7. Technical Meta Tag Inspector & Heading Auditor ──
export function runMetaTagAnalyzer(input: string): ToolExecutionResult {
  const startTime = performance.now();
  if (!input.trim()) {
    return {
      success: false,
      output: '',
      error: { message: 'Paste HTML head markup to inspect technical SEO meta tags.' },
      telemetry: { executionTimeMs: 0, inputChars: 0, outputChars: 0 },
    };
  }

  // Regex extractors
  const titleMatch = input.match(/<title[^>]*>([^<]*)<\/title>/i);
  const descMatch = input.match(/<meta[^>]*name=["']description["'][^>]*content=["']([^"']*)["']/i) ||
                    input.match(/<meta[^>]*content=["']([^"']*)["'][^>]*name=["']description["']/i);
  const canonicalMatch = input.match(/<link[^>]*rel=["']canonical["'][^>]*href=["']([^"']*)["']/i);
  const viewportMatch = input.match(/<meta[^>]*name=["']viewport["'][^>]*content=["']([^"']*)["']/i);
  const robotsMatch = input.match(/<meta[^>]*name=["']robots["'][^>]*content=["']([^"']*)["']/i);
  const ogTitleMatch = input.match(/<meta[^>]*property=["']og:title["'][^>]*content=["']([^"']*)["']/i);
  const ogImageMatch = input.match(/<meta[^>]*property=["']og:image["'][^>]*content=["']([^"']*)["']/i);

  const issues: string[] = [];
  const passes: string[] = [];
  let score = 100;

  if (titleMatch && titleMatch[1].trim()) {
    const len = titleMatch[1].trim().length;
    if (len >= 30 && len <= 60) {
      passes.push(`Title tag is optimal length (${len} chars): "${titleMatch[1].trim()}"`);
    } else {
      issues.push(`Title tag length is sub-optimal (${len} chars). Recommended range: 40-60 characters.`);
      score -= 10;
    }
  } else {
    issues.push(`CRITICAL: <title> tag is missing entirely.`);
    score -= 30;
  }

  if (descMatch && descMatch[1].trim()) {
    const len = descMatch[1].trim().length;
    if (len >= 120 && len <= 160) {
      passes.push(`Meta description is optimal length (${len} chars).`);
    } else {
      issues.push(`Meta description length is ${len} chars. Recommended range: 120-160 characters.`);
      score -= 10;
    }
  } else {
    issues.push(`CRITICAL: Meta description tag is missing.`);
    score -= 25;
  }

  if (canonicalMatch && canonicalMatch[1].trim()) {
    passes.push(`Canonical URL link tag detected: ${canonicalMatch[1].trim()}`);
  } else {
    issues.push(`WARNING: Missing canonical URL link tag (<link rel="canonical" href="...">).`);
    score -= 15;
  }

  if (viewportMatch) {
    passes.push(`Mobile Viewport tag is configured properly.`);
  } else {
    issues.push(`WARNING: Missing mobile viewport meta tag.`);
    score -= 10;
  }

  if (ogTitleMatch && ogImageMatch) {
    passes.push(`Social Open Graph metadata (og:title, og:image) is present.`);
  } else {
    issues.push(`NOTICE: Missing complete Open Graph tags for social media sharing.`);
    score -= 10;
  }

  let out = `TECHNICAL SEO AUDIT REPORT (Score: ${Math.max(0, score)}/100)\n`;
  out += `====================================================\n\n`;

  out += `PASSED CHECKS (${passes.length}):\n`;
  passes.forEach((p) => (out += `✓ ${p}\n`));
  out += `\n`;

  out += `ISSUES & OPTIMIZATIONS FOUND (${issues.length}):\n`;
  issues.forEach((iss) => (out += `✗ ${iss}\n`));

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: out,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: out.length },
    meta: { score: Math.max(0, score), passes, issues },
  };
}

// ── 8. Heading Hierarchy (H1-H6) Tree Analyzer ──
export function runHeadingStructureAnalyzer(input: string): ToolExecutionResult {
  const startTime = performance.now();
  if (!input.trim()) {
    return {
      success: false,
      output: '',
      error: { message: 'Paste HTML or Markdown to analyze the heading structure hierarchy.' },
      telemetry: { executionTimeMs: 0, inputChars: 0, outputChars: 0 },
    };
  }

  const headings: Array<{ level: number; text: string }> = [];

  // Match HTML headings
  const htmlRegex = /<(h[1-6])[^>]*>([\s\S]*?)<\/\1>/gi;
  let match;
  while ((match = htmlRegex.exec(input)) !== null) {
    const level = parseInt(match[1][1], 10);
    const text = match[2].replace(/<[^>]+>/g, '').trim();
    headings.push({ level, text });
  }

  // If no HTML headings found, match Markdown headings
  if (headings.length === 0) {
    const mdRegex = /^(#{1,6})\s+(.+)$/gm;
    while ((match = mdRegex.exec(input)) !== null) {
      headings.push({ level: match[1].length, text: match[2].trim() });
    }
  }

  if (headings.length === 0) {
    return {
      success: true,
      output: `No H1-H6 headings detected in the provided markup.`,
      telemetry: { executionTimeMs: 0, inputChars: input.length, outputChars: 50 },
    };
  }

  const warnings: string[] = [];
  const h1Count = headings.filter((h) => h.level === 1).length;

  if (h1Count === 0) {
    warnings.push(`CRITICAL: Page has 0 H1 tags. Exactly one H1 is recommended for primary topic relevance.`);
  } else if (h1Count > 1) {
    warnings.push(`WARNING: Page has ${h1Count} H1 tags. Recommended standard is a single unique H1.`);
  }

  let prevLevel = 1;
  headings.forEach((h, i) => {
    if (i > 0 && h.level > prevLevel + 1) {
      warnings.push(`SKIPPED LEVEL: Jumped from H${prevLevel} directly to H${h.level} ("${h.text}"). Recommended: sequential nesting.`);
    }
    prevLevel = h.level;
  });

  let tree = `HEADING HIERARCHY TREE\n`;
  tree += `====================================================\n\n`;

  headings.forEach((h) => {
    const indent = '  '.repeat(h.level - 1);
    tree += `${indent}[H${h.level}] ${h.text || '(Empty Heading)'}\n`;
  });

  tree += `\nAUDIT DIAGNOSTICS (${warnings.length} warnings):\n`;
  if (warnings.length === 0) {
    tree += `✓ Clean, perfectly ordered heading outline. No skipped levels.\n`;
  } else {
    warnings.forEach((w) => (tree += `• ${w}\n`));
  }

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: tree,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: tree.length },
    meta: { totalHeadings: headings.length, h1Count, warnings, headings },
  };
}

// ── 9. Keyword Density & N-Gram Tokenizer ──
export function runKeywordDensityChecker(input: string): ToolExecutionResult {
  const startTime = performance.now();
  // Strip HTML
  const clean = input.replace(/<[^>]+>/g, ' ').replace(/[^\w\s-]/g, ' ').toLowerCase();
  const rawTokens = clean.split(/\s+/).filter((t) => t.length > 2);
  const totalWords = rawTokens.length;

  if (totalWords === 0) {
    return {
      success: false,
      output: '',
      error: { message: 'Provide text content to calculate keyword frequency and density.' },
      telemetry: { executionTimeMs: 0, inputChars: 0, outputChars: 0 },
    };
  }

  // Filter stop words
  const contentWords = rawTokens.filter((w) => !STOP_WORDS.has(w));

  // 1-gram
  const singleGramMap = new Map<string, number>();
  contentWords.forEach((w) => singleGramMap.set(w, (singleGramMap.get(w) || 0) + 1));

  // 2-gram
  const twoGramMap = new Map<string, number>();
  for (let i = 0; i < rawTokens.length - 1; i++) {
    const w1 = rawTokens[i];
    const w2 = rawTokens[i + 1];
    if (!STOP_WORDS.has(w1) || !STOP_WORDS.has(w2)) {
      const phrase = `${w1} ${w2}`;
      twoGramMap.set(phrase, (twoGramMap.get(phrase) || 0) + 1);
    }
  }

  const sortTop = (map: Map<string, number>, limit = 8) =>
    Array.from(map.entries())
      .sort((a, b) => b[1] - a[1])
      .slice(0, limit);

  const top1 = sortTop(singleGramMap, 8);
  const top2 = sortTop(twoGramMap, 6);

  let out = `KEYWORD DENSITY & N-GRAM ANALYSIS REPORT\n`;
  out += `====================================================\n`;
  out += `Total Word Count: ${totalWords} words\n`;
  out += `Content Words (Excluding Stop Words): ${contentWords.length}\n\n`;

  out += `TOP 1-GRAM KEYWORDS:\n`;
  out += `Keyword               Count    Density    Risk\n`;
  out += `----------------------------------------------------\n`;
  top1.forEach(([k, count]) => {
    const density = ((count / totalWords) * 100).toFixed(2);
    const risk = Number(density) > 3.5 ? '⚠️ HIGH DENSITY' : '✓ Natural';
    out += `${k.padEnd(20)}  ${String(count).padEnd(6)}  ${density.padStart(5)}%     ${risk}\n`;
  });
  out += `\n`;

  out += `TOP 2-GRAM PHRASES:\n`;
  out += `Phrase                          Count    Density\n`;
  out += `----------------------------------------------------\n`;
  top2.forEach(([k, count]) => {
    const density = ((count / totalWords) * 100).toFixed(2);
    out += `${k.padEnd(30)}  ${String(count).padEnd(6)}  ${density.padStart(5)}%\n`;
  });

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: out,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: out.length },
    meta: { totalWords, top1, top2 },
  };
}

// ── 10. URL Slug Sanitizer & Permanent Redirection Rule Builder ──
export function runSlugGenerator(input: string, options?: Record<string, any>): ToolExecutionResult {
  const startTime = performance.now();
  const delimiter = options?.delimiter || '-';
  const oldUrl = (options?.oldUrl || '/old-article-path').trim();

  const slug = input
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // strip accents
    .replace(/[^\w\s-]/g, '')        // strip symbols
    .trim()
    .replace(/[\s_-]+/g, delimiter)  // replace spaces with delimiter
    .replace(new RegExp(`^\\${delimiter}+|\\${delimiter}+$`, 'g'), ''); // trim delimiters

  let out = `SANITIZED URL SLUG:\n${slug}\n\n`;
  out += `SERVER 301 PERMANENT REDIRECT DIRECTIVES:\n`;
  out += `----------------------------------------------------\n`;
  out += `# Apache .htaccess\n`;
  out += `RedirectMatch 301 ^${oldUrl}/?$ /${slug}\n\n`;
  out += `# NGINX Configuration\n`;
  out += `rewrite ^${oldUrl}/?$ /${slug} permanent;\n\n`;
  out += `# Next.js next.config.js redirects block\n`;
  out += `{\n`;
  out += `  source: '${oldUrl}',\n`;
  out += `  destination: '/${slug}',\n`;
  out += `  permanent: true,\n`;
  out += `}\n`;

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: out,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: out.length },
    meta: { slug, oldUrl },
  };
}

// ── 11. Image Alt-Text Quality Inspector ──
export function runImageAltSeoHelper(input: string): ToolExecutionResult {
  const startTime = performance.now();
  const imgRegex = /<img\s+([^>]+)>/gi;
  const images: Array<{ tag: string; src: string; alt: string; issue?: string }> = [];

  let match;
  while ((match = imgRegex.exec(input)) !== null) {
    const attrs = match[1];
    const srcMatch = attrs.match(/src=["']([^"']+)["']/i);
    const altMatch = attrs.match(/alt=["']([^"']*)["']/i);

    const src = srcMatch ? srcMatch[1] : 'unknown-src';
    const alt = altMatch ? altMatch[1] : '';

    let issue = '';
    if (!altMatch) issue = 'Missing alt attribute entirely';
    else if (!alt.trim()) issue = 'Empty alt="" description';
    else if (/^(image|photo|pic|screenshot|logo|banner)$/i.test(alt.trim())) {
      issue = `Generic, low-value alt description: "${alt}"`;
    }

    images.push({ tag: match[0], src, alt, issue });
  }

  if (images.length === 0) {
    return {
      success: true,
      output: `No <img> elements found in the supplied HTML markup.`,
      telemetry: { executionTimeMs: 0, inputChars: input.length, outputChars: 45 },
    };
  }

  const issuesCount = images.filter((i) => i.issue).length;
  let out = `IMAGE ACCESSIBILITY & TECHNICAL SEO ALT AUDIT\n`;
  out += `====================================================\n`;
  out += `Total Images Scanned: ${images.length}\n`;
  out += `Images Requiring Optimization: ${issuesCount}\n\n`;

  images.forEach((img, idx) => {
    out += `[Image #${idx + 1}] Source: ${img.src}\n`;
    out += `• Current Alt: ${img.alt ? `"${img.alt}"` : '(None)'}\n`;
    if (img.issue) {
      out += `• Status: ⚠️ ${img.issue}\n`;
      // Generate clean context-aware alt suggestion from file basename
      const fileName = img.src.split('/').pop()?.split('.')[0]?.replace(/[-_]+/g, ' ') || 'product visual';
      out += `• Recommended Fix: alt="${fileName.charAt(0).toUpperCase() + fileName.slice(1)} diagram"\n`;
    } else {
      out += `• Status: ✓ Descriptive and valid\n`;
    }
    out += `\n`;
  });

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: out,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: out.length },
    meta: { totalImages: images.length, issuesCount },
  };
}

// ── 12. Internal vs. External Link Extractor & Rel Auditor ──
export function runLinkExtractor(input: string, options?: Record<string, any>): ToolExecutionResult {
  const startTime = performance.now();
  const currentDomain = (options?.domain || 'aiiseverything.com').replace(/^https?:\/\//, '').toLowerCase();

  const aRegex = /<a\s+([^>]+)>([\s\S]*?)<\/a>/gi;
  const links: Array<{
    href: string;
    text: string;
    type: 'INTERNAL' | 'EXTERNAL' | 'ANCHOR' | 'PROTOCOL';
    rel: string;
    target: string;
    securityWarning?: string;
  }> = [];

  let match;
  while ((match = aRegex.exec(input)) !== null) {
    const attrs = match[1];
    const text = match[2].replace(/<[^>]+>/g, '').trim();

    const hrefMatch = attrs.match(/href=["']([^"']*)["']/i);
    const relMatch = attrs.match(/rel=["']([^"']*)["']/i);
    const targetMatch = attrs.match(/target=["']([^"']*)["']/i);

    const href = hrefMatch ? hrefMatch[1].trim() : '';
    const rel = relMatch ? relMatch[1].trim() : '';
    const target = targetMatch ? targetMatch[1].trim() : '';

    let type: 'INTERNAL' | 'EXTERNAL' | 'ANCHOR' | 'PROTOCOL' = 'INTERNAL';
    if (href.startsWith('#')) type = 'ANCHOR';
    else if (/^(mailto:|tel:|javascript:)/i.test(href)) type = 'PROTOCOL';
    else if (/^https?:\/\//i.test(href)) {
      type = href.toLowerCase().includes(currentDomain) ? 'INTERNAL' : 'EXTERNAL';
    }

    let securityWarning = '';
    if (type === 'EXTERNAL' && target === '_blank' && !rel.includes('noopener')) {
      securityWarning = 'External link with target="_blank" is missing rel="noopener" (tabnabbing vulnerability)';
    }

    links.push({ href, text, type, rel, target, securityWarning });
  }

  const internalCount = links.filter((l) => l.type === 'INTERNAL').length;
  const externalCount = links.filter((l) => l.type === 'EXTERNAL').length;
  const warningsCount = links.filter((l) => l.securityWarning).length;

  let out = `LINK EXTRACTION & ATTRIBUTE AUDIT REPORT\n`;
  out += `====================================================\n`;
  out += `Total Links Extracted: ${links.length}\n`;
  out += `• Internal Links: ${internalCount}\n`;
  out += `• External Links: ${externalCount}\n`;
  out += `• Security Flags: ${warningsCount}\n\n`;

  links.forEach((l, idx) => {
    out += `[#${idx + 1}] [${l.type}] "${l.text || '(No anchor text)'}" → ${l.href}\n`;
    if (l.rel) out += `  rel: "${l.rel}" | target: "${l.target}"\n`;
    if (l.securityWarning) out += `  ⚠️ ${l.securityWarning}\n`;
  });

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: out,
    telemetry: { executionTimeMs, inputChars: input.length, outputChars: out.length },
    meta: { total: links.length, internalCount, externalCount, warningsCount },
  };
}
