// ── 1. Robots.txt Generator & Directives Validator ──
export function runRobotsTxtGenerator(input: string, options?: Record<string, any>): ToolExecutionResult {
  const startTime = performance.now();
  const domain = (options?.domain || 'https://example.com').trim().replace(/\/+$/, '');
  const sitemapUrl = (options?.sitemap || `${domain}/sitemap.xml`).trim();
  const allowAiCrawlers = options?.allowAiCrawlers !== false;
  const crawlDelay = Number(options?.crawlDelay) || 0;

  // Custom paths from input
  const lines = input.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  const disallowPaths = new Set<string>();
  const allowPaths = new Set<string>();

  for (const line of lines) {
    if (line.toLowerCase().startsWith('disallow:')) {
      disallowPaths.add(line.substring(9).trim());
    } else if (line.toLowerCase().startsWith('allow:')) {
      allowPaths.add(line.substring(6).trim());
    } else if (line.startsWith('/')) {
      disallowPaths.add(line);
    }
  }

  // Defaults if nothing specified
  if (disallowPaths.size === 0) {
    disallowPaths.add('/admin/');
    disallowPaths.add('/api/private/');
    disallowPaths.add('/dashboard/settings/');
  }

  let output = `# ====================================================================\n`;
  output += `# Robots.txt Generated by AIIsEverything Technical SEO Engine\n`;
  output += `# Host: ${domain}\n`;
  output += `# Generated: ${new Date().toISOString().split('T')[0]}\n`;
  output += `# ====================================================================\n\n`;

  // Standard Web Crawlers
  output += `# Standard Search Engine Crawlers\n`;
  output += `User-agent: *\n`;
  if (allowPaths.size > 0) {
    allowPaths.forEach((p) => (output += `Allow: ${p}\n`));
  } else {
    output += `Allow: /\n`;
  }
  disallowPaths.forEach((p) => (output += `Disallow: ${p}\n`));
  if (crawlDelay > 0) output += `Crawl-delay: ${crawlDelay}\n`;
  output += `\n`;

  // Specialized AI Agents Block
  output += `# Generative AI & LLM Indexing Directives\n`;
  const aiBots = ['GPTBot', 'ClaudeBot', 'PerplexityBot', 'CCBot', 'Google-Extended'];
  for (const bot of aiBots) {
    output += `User-agent: ${bot}\n`;
    if (allowAiCrawlers) {
      output += `Allow: /\n`;
      disallowPaths.forEach((p) => (output += `Disallow: ${p}\n`));
    } else {
      output += `Disallow: /\n`;
    }
    output += `\n`;
  }

  // Sitemap Reference
  output += `# Canonical XML Sitemaps\n`;
  output += `Sitemap: ${sitemapUrl}\n`;

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output,
    telemetry: {
      executionTimeMs,
      inputChars: input.length,
      outputChars: output.length,
    },
    meta: {
      domain,
      sitemapUrl,
      disallowedCount: disallowPaths.size,
      aiCrawlersAllowed: allowAiCrawlers,
    },
  };
}

// ── 2. XML Sitemap Generator & Tag Validator ──
export function runXmlSitemapGenerator(input: string, options?: Record<string, any>): ToolExecutionResult {
  const startTime = performance.now();
  const rawUrls = input.split(/[\r\n,]+/).map((u) => u.trim()).filter(Boolean);

  if (rawUrls.length === 0) {
    return {
      success: false,
      output: '',
      error: { message: 'Please provide at least one valid URL to generate an XML sitemap.' },
      telemetry: { executionTimeMs: 0, inputChars: 0, outputChars: 0 },
    };
  }

  const changefreq = options?.changefreq || 'weekly';
  const priority = options?.priority || '0.8';
  const now = new Date().toISOString().split('T')[0];

  const validUrls: string[] = [];
  const invalidUrls: string[] = [];

  for (const raw of rawUrls) {
    try {
      const parsed = new URL(raw.startsWith('http') ? raw : `https://${raw}`);
      // Escape XML characters
      const escaped = parsed.toString()
        .replace(/&/g, '&amp;')
        .replace(/'/g, '&apos;')
        .replace(/"/g, '&quot;')
        .replace(/>/g, '&gt;')
        .replace(/</g, '&lt;');
      validUrls.push(escaped);
    } catch {
      invalidUrls.push(raw);
    }
  }

  let xml = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  xml += `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n`;
  xml += `        xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"\n`;
  xml += `        xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9\n`;
  xml += `        http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd">\n`;

  validUrls.forEach((url, i) => {
    const p = i === 0 ? '1.0' : priority;
    const cf = i === 0 ? 'daily' : changefreq;
    xml += `  <url>\n`;
    xml += `    <loc>${url}</loc>\n`;
    xml += `    <lastmod>${now}</lastmod>\n`;
    xml += `    <changefreq>${cf}</changefreq>\n`;
    xml += `    <priority>${p}</priority>\n`;
    xml += `  </url>\n`;
  });

  xml += `</urlset>`;

  const executionTimeMs = Math.round((performance.now() - startTime) * 100) / 100;
  return {
    success: true,
    output: xml,
    telemetry: {
      executionTimeMs,
      inputChars: input.length,
      outputChars: xml.length,
    },
    meta: {
      totalParsed: rawUrls.length,
      validUrlsCount: validUrls.length,
      invalidUrls,
    },
  };
}

